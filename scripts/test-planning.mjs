import assert from 'node:assert/strict';
import { periodBounds,movePeriod,dateKey,summarizeRevenue,calendarLanes,daySegments,foreground,entityColor } from '../lib/planning.mjs';
const zone='America/Sao_Paulo',day='2026-09-23';
const services=[{id:'cut',name:'Corte',price:50},{id:'free',name:'Cortesia',price:0},{id:'none',name:'Sem preço',price:null}];
const booking=(id,overrides={})=>({id,service_id:'cut',starts_at:'2026-09-23T13:00:00Z',ends_at:'2026-09-23T14:00:00Z',status:'completed',...overrides});
assert.deepEqual(periodBounds('2026-09-27','Semana'),['2026-09-21','2026-09-28']);
assert.deepEqual(periodBounds('2026-12-31','Mês'),['2026-12-01','2027-01-01']);
assert.equal(movePeriod('2024-01-31','Mês',1),'2024-02-29');
assert.equal(dateKey('2026-09-24T02:59:00Z',zone),day);
assert.equal(summarizeRevenue([booking('1'),booking('2')],services,day,'Dia',zone).totalCents,10000);
assert.equal(summarizeRevenue([booking('1',{status:'cancelled'}),booking('2',{status:'confirmed'}),booking('3',{status:'no_show'})],services,day,'Dia',zone).count,0);
const fixed=booking('1',{charged_price:50,price_source:'at_completion'});
assert.equal(summarizeRevenue([fixed],[{id:'cut',price:100}],day,'Mês',zone).totalCents,5000);
const mix=summarizeRevenue([fixed,booking('2',{service_id:'none'}),booking('3',{service_id:'free'})],services,day,'Dia',zone);
assert.equal(mix.count,3);assert.equal(mix.missing,1);assert.equal(mix.totalCents,5000);
assert.equal(summarizeRevenue([booking('1',{charged_price:null,price_source:'unpriced'})],services,day,'Dia',zone).missing,1);
assert.equal(summarizeRevenue([booking('1',{starts_at:'2026-09-24T03:00:00Z'})],services,day,'Dia',zone).count,0);
assert.equal(summarizeRevenue([booking('1',{starts_at:'2026-09-24T02:59:00Z'})],services,day,'Dia',zone).count,1);
const lanes=calendarLanes([{start:600,end:660},{start:610,end:630},{start:630,end:680},{start:700,end:730}]);
assert.deepEqual(lanes.map(x=>[x.lane,x.lanes]),[[0,2],[1,2],[1,2],[0,1]]);
const midnight=booking('1',{starts_at:'2026-09-24T02:30:00Z',ends_at:'2026-09-24T03:30:00Z'});
assert.deepEqual(daySegments([midnight],day,zone).map(x=>[x.start,x.end]),[[1410,1440]]);
assert.deepEqual(daySegments([midnight],'2026-09-24',zone).map(x=>[x.start,x.end]),[[0,30]]);
assert.equal(daySegments([booking('1',{starts_at:'2026-09-24T02:00:00Z',ends_at:'2026-09-24T03:00:00Z'})],'2026-09-24',zone).length,0);
assert.equal(foreground('#ffffff'),'#081b30');assert.equal(foreground('#000000'),'#ffffff');
assert.equal(entityColor('cut',{cut:'#ff00aa'}),'#ff00aa');
console.log('20 verificações de calendário, cores e financeiro passaram.');
